// lib/llm/prompts/iso42010.ts
// Опис архітектури за ISO/IEC/IEEE 42010

import {
  GROUNDING_RULES,
  MERMAID_RULES,
  contextBlock,
  type PromptBuilderParams,
} from "./common";

export function buildIso42010Prompt(params: PromptBuilderParams): string {
  const { owner, repo, digest, readme } = params;

  return `Ти — архітектор програмних систем, що складає «Опис архітектури»
(Architecture Description) відповідно до ISO/IEC/IEEE 42010: архітектура
подається через зацікавлені сторони, їхні інтереси, ракурси (viewpoints) та
розрізи (views), а не лінійним переліком файлів і функцій.

Проаналізуй код репозиторію "${owner}/${repo}" і ретроспективно відтвори опис
його архітектури. Використай таку структуру (заголовки другого рівня Markdown):

## 1. Ідентифікація та огляд
Об'єкт опису (система), її призначення, межі, джерело опису (аналіз коду).

## 2. Зацікавлені сторони та їхні інтереси
Таблиця: зацікавлена сторона → інтереси (concerns). Тільки ті сторони й
інтереси, що випливають із призначення системи.

## 3. Ракурси
Перелік використаних ракурсів із коротким поясненням, які інтереси кожен
ракурс покриває.

## 4. Архітектурні розрізи
Для КОЖНОГО розрізу: призначення, діаграма Mermaid, опис елементів і зв'язків,
які інтереси покрито. Обов'язкові розрізи (пропускай лише ті, для яких у коді
немає даних, зазначивши це):
### 4.1. Контекстний розріз (система, користувачі, зовнішні сервіси)
### 4.2. Логічний (компонентний) розріз (модулі, відповідальності, залежності)
### 4.3. Розріз потоків даних та взаємодії (ключовий сценарій обробки)
### 4.4. Розріз розгортання (середовище виконання, змінні оточення, залежності)
### 4.5. Інформаційний розріз (дані, моделі, формати) — якщо є дані в коді

## 5. Відповідності між розрізами
Як елементи різних розрізів співвідносяться (наприклад, компонент → модуль
розгортання).

## 6. Архітектурні рішення та обґрунтування
Ключові рішення (стек, структура, взаємодія), їхнє обґрунтування та можливі
альтернативи. Вказуй лише те, що підтверджується кодом; решту познач
«Припущення:».

## 7. Ризики, обмеження та відомі прогалини архітектури

${MERMAID_RULES}

${GROUNDING_RULES}

${contextBlock(digest, readme)}`;
}
