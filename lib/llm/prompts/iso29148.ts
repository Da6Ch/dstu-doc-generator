// lib/llm/prompts/iso29148.ts
// Специфікація вимог до ПЗ (SRS) за ISO/IEC/IEEE 29148

import {
  GROUNDING_RULES,
  contextBlock,
  type PromptBuilderParams,
} from "./common";

export function buildIso29148Prompt(params: PromptBuilderParams): string {
  const { owner, repo, digest, readme } = params;

  return `Ти — інженер з вимог, що складає «Специфікацію вимог до програмного
забезпечення» (Software Requirements Specification, SRS) відповідно до
ISO/IEC/IEEE 29148 (процеси життєвого циклу, інженерія вимог).

Проаналізуй код репозиторію "${owner}/${repo}" і ретроспективно відтвори
специфікацію вимог до системи. Використай таку структуру (заголовки другого
рівня Markdown):

## 1. Вступ
### 1.1. Призначення документа
### 1.2. Межі системи (scope)
### 1.3. Огляд продукту
#### 1.3.1. Контекст продукту (перспектива)
#### 1.3.2. Функції продукту (узагальнено)
#### 1.3.3. Характеристики користувачів
#### 1.3.4. Обмеження
### 1.4. Визначення, терміни та скорочення

## 2. Нормативні та інші посилання
Лише ті документи й технології, на які реально спирається проєкт.

## 3. Специфічні вимоги
### 3.1. Зовнішні інтерфейси (користувацькі, програмні, API, зовнішні сервіси)
### 3.2. Функціональні вимоги
### 3.3. Вимоги до зручності використання
### 3.4. Вимоги до продуктивності
### 3.5. Вимоги до даних (логічна модель даних, якщо є)
### 3.6. Проєктні обмеження (технології, стандарти, середовище)
### 3.7. Атрибути якості системи (надійність, безпека, супровід, переносимість)

## 4. Верифікація
Для кожної групи вимог — спосіб перевірки (тест, огляд, демонстрація,
аналіз), з урахуванням того, що реально є в проєкті (тести, CI тощо).

## 5. Додатки
Припущення та залежності; матриця відстеження «вимога → файл-джерело».

ВИМОГИ ДО ФОРМУЛЮВАННЯ ВИМОГ (за ISO/IEC/IEEE 29148):
- Кожна вимога має унікальний ідентифікатор: FR-001, FR-002 (функціональні),
  NFR-001 (нефункціональні), IR-001 (інтерфейсні).
- Формулюй у вигляді «Система повинна …», одне твердження на вимогу.
- Вимога має бути однозначною, перевірюваною й не містити двозначних слів
  («швидко», «зручно», «тощо»).
- До кожної вимоги, виведеної з коду, додай джерело у дужках, наприклад
  (джерело: \`app/api/generate/route.ts\`).
- Вимоги, яких у коді не видно, але які типові для такого класу систем,
  виносити окремо з позначкою «Припущення:».

${GROUNDING_RULES}

${contextBlock(digest, readme)}`;
}
